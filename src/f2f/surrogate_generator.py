""""
Stream 5: Activity-driven network generator in the contact-table format.
"""

import numpy as np
import pandas as pd
from f2f.datasets import WINDOW_S

def group_contacts_by_day(contacts):
    """ 
        Groups the contact rows by day and finds the earliest and latest timestamps for each day. 
        The difference between start end end times from day >=1 for school data, is caused because of 
        no contact recorded overnight.
    """
    return contacts.groupby("day")["t"].agg(start="min", end="max").astype(int)

def generate_surrogate(nodes, activity, schedule, origin, m, eta, seed):
    """
        An activity-driven network. With this surrogate model, we can answer
        "Are differences in how active people are enough to reproduce the important network features and outbreak behaviour?"

        Params:
            nodes: Table of people, its index is the people's IDs
            activity: Contains each people's activity x_i , indexed with corresponding ID
            schedule: Contains the earliest and lates timestamps for each day, generated by group_contacts_by_day()
            origin: Absolute day and time corresponding to t=0
            m: Number of distinct people chosen by an active person
            eta: Activity multiplier
            seed: Random seed for reproducibility

    """
    # Get IDs 
    ids = nodes.index.to_numpy()
    n = len(ids)

    # Order the activities based on the indexes so activities line up with correct people
    ordered_activities = activity.reindex(nodes.index).to_numpy()

    # Check m and x has valid values
    if not 1<=m<n:
        raise ValueError("m must be between 1 and N-1")
    if not np.isfinite(ordered_activities).all() or (ordered_activities < 0).any():
        raise ValueError("There are invalid activity values")
    
    # Convert activity shares into activation probabilities per 20-second window
    activation_prob = eta * ordered_activities

    # Validate probability and time
    if (eta < 0) or (activation_prob > 1).any():
        raise ValueError("Probability should be between 0 and 1")

    rng = np.random.default_rng(seed)
    record = []

    # Visit every window
    for day, interval in schedule.iterrows():
        for t in range(int(interval.start), int(interval.end) + 1, WINDOW_S):
            # Get active people by checking if the randomly selected number is below their activation probability
            active_people = np.flatnonzero(rng.random(n) < activation_prob)

            contact_pairs = set()
            
            for person in active_people:
                candidates = np.arange(n)
                candidates = candidates[candidates != person] # Exclude chosen active person from candidates
                # Sample random people that the active person can contact
                partners = rng.choice(candidates, size=m, replace=False)

                for partner in partners:
                    # Store each undirected contact with the smaller ID first
                    a, b = sorted((int(ids[person]), int(ids[partner])))
                    contact_pairs.add((a,b))
                
            # Store contact pairs under window 
            record.extend((t, a, b, int(day)) for a, b in sorted(contact_pairs))
    
    result = pd.DataFrame(record, columns=["t", "i", "j", "day"])
    result["abs_time"] = origin + pd.to_timedelta(result["t"], unit="s")
    result = result[["t", "i", "j", "abs_time", "day"]].sort_values(["t", "i", "j"]).reset_index(drop=True)

    return result

def calculate_daily_stats(contacts, nodes, days):
    """
    For each requested day, it returns:
            - The degree CDF gives the fraction of nodes with degree <= k.
            - Contact volume counts pair-windows, including repeated pairs.
    Nodes without contacts are included with degree zero.
    """
    distinct_partners, total_windows = [], []

    for day in days:
        daily = contacts.loc[contacts["day"].eq(day)]

        # Remove repeated meetings between the same pair for calculating degree
        pairs = daily[["i", "j"]].drop_duplicates()

        # Calculate how often each person appears in the distinct pairs
        endpoints = pd.concat([pairs["i"], pairs["j"]], ignore_index=True)
        degrees = (endpoints.value_counts().reindex(nodes.index, fill_value=0).to_numpy(dtype=int))

        # Calculate the degree distribution
        degree_dist = np.bincount(degrees, minlength=len(nodes)) / len(nodes)
        distinct_partners.append(np.cumsum(degree_dist))
        total_windows.append(len(daily))

    return np.asarray(distinct_partners), np.asarray(total_windows, dtype=float)

def compare_networks(observed_network_prop, generated_network_prop):
    """
        Return degree-CDF MSE and relative contact-volume MSE.
    """
    real_dd, real_cw = observed_network_prop
    generated_dd, generated_cw = generated_network_prop

    degree_dist_diff = np.mean((real_dd - generated_dd) ** 2)
    contact_window_diff = np.mean(((generated_cw - real_cw) / np.maximum(real_cw, 1)) ** 2)

    return degree_dist_diff, contact_window_diff
